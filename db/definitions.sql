CREATE TABLE WINE (
    ID INTEGER AUTO_INCREMENT,
    WINE_NAME VARCHAR(50) NOT NULL DEFAULT('TURBO vino'),
    ID_LIQUIDATOR INTEGER,
    ID_SELL_APPROVER INTEGER,
    ID_PICTURE INTEGER,
    YEAR SMALLINT NOT NULL,
    ALCOHOL_PERCENTAGE TINYINT NOT NULL DEFAULT(13),
    TYPE ENUM('DRY', 'HALF_DRY', 'HALF_SWEET', 'SWEET') NOT NULL DEFAULT('DRY'),
    COLOR ENUM('WHITE', 'RED', 'PINK') NOT NULL DEFAULT('WHITE'),
    GRADE ENUM('NONE', 'CABINET', 'LATE', 'GRAPE_SELECTION', 'BERRY_SELECTION', 'ICE', 'STRAW') NOT NULL DEFAULT('NONE'),
    STATE ENUM('PRODUCTION', 'LIQUIDATED', 'BOTTLED', 'SALE', 'SOLD') NOT NULL DEFAULT ('PRODUCTION'),
    VOLUME SMALLINT NOT NULL,
    BOTTLE_PRICE SMALLINT,
    CURRENT_PRICE SMALLINT,
    BOTTLES_LEFT SMALLINT,
    LEFT_SUGAR TINYINT,
    ACID_CONTENTS TINYINT,
    SALES_DESCRIPTION TEXT,
    PRODUCTION_NOTE TEXT NOT NULL DEFAULT(''),
    CONSTRAINT PK_WINE PRIMARY KEY (ID),
    CONSTRAINT
        FK_ID_LIQUIDATOR
        FOREIGN KEY (ID_LIQUIDATOR)
        REFERENCES USER (ID)
        ON DELETE SET NULL,
    CONSTRAINT
        FK_ID_SELL_APPROVER
        FOREIGN KEY (ID_SELL_APPROVER)
        REFERENCES USER (ID)
        ON DELETE SET NULL,
    CONSTRAINT
        FK_ID_PICTURE
        FOREIGN KEY (ID_PICTURE)
        REFERENCES PICTURE (ID)
        ON DELETE SET NULL
);

